// E-mail can't read CSS variables, so the AXLE colours an e-mail uses are written out from app/axle-tokens.css.
// npm run mail:colours after a token sync; tests/unit/mail.test.ts fails while lib/mail/axle-colours.ts is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const USED = ["bar", "bar-ink", "bar-muted", "orange", "on-orange", "orange-tint", "orange-text", "page", "card", "card-line", "text-strong", "text", "text-muted", "link", "info-tint", "info-line"];

export function mailColours(css) {
  const out = {};
  for (const name of USED) {
    const m = css.match(new RegExp(`--axle-${name}:\\s*([^;]+);`));
    if (!m) throw new Error(`--axle-${name} is not in axle-tokens.css`);
    out[name.replace(/-(\w)/g, (_, c) => c.toUpperCase())] = m[1].trim();
  }
  return out;
}

export function mailColoursSource(css) {
  return `// GENERATED by scripts/mail-colours.mjs from app/axle-tokens.css: do not edit. npm run mail:colours to refresh.\nexport const AXLE_MAIL = ${JSON.stringify(mailColours(css), null, 2)} as const;\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync("lib/mail/axle-colours.ts", mailColoursSource(readFileSync("app/axle-tokens.css", "utf8")));
  console.log("wrote lib/mail/axle-colours.ts");
}
